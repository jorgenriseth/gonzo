"""Generate the standalone release manifest from the root development manifest."""

import argparse
import copy
import json
import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load(path):
    with path.open("rb") as stream:
        return tomllib.load(stream)


def dump_tables(data, prefix=()):
    lines = []
    if prefix:
        lines.append("[" + ".".join(prefix) + "]")
    for key, value in data.items():
        if not re.fullmatch(r"[A-Za-z0-9_-]+", key):
            raise ValueError(f"Unsupported manifest key: {key}")
        if not isinstance(value, dict):
            lines.append(f"{key} = {json.dumps(value)}")
    lines.append("")
    for key, value in data.items():
        if isinstance(value, dict):
            lines.extend(dump_tables(value, (*prefix, key)))
    return lines


def manifest(library, channel=None):
    """Release manifest: the root manifest's shared part, with the editable
    gmri2fem feature replaced by the released FSL companion package."""
    root = load(ROOT / "pixi.toml")
    policy = load(library / "conda-recipe/fsl.toml")["package"]
    pixi = {key: copy.deepcopy(root[key]) for key in ("workspace", "dependencies", "activation")}
    pixi["workspace"]["name"] = "gonzo-release"
    if channel:
        pixi["workspace"]["channels"].insert(0, Path(channel).resolve().as_uri())
    pixi["dependencies"][policy["name"]] = f"=={policy['version']}"
    return pixi


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gmri2fem", type=Path, default=ROOT.parent / "gmri2fem")
    parser.add_argument("--channel", type=Path, help="Local channel for pre-publication testing")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="Check an existing generated manifest")
    args = parser.parse_args()
    text = "# Generated by scripts/prepare_environment.py; do not edit.\n"
    text += "\n".join(dump_tables(manifest(args.gmri2fem, args.channel)))
    if args.check:
        if args.output.read_text() != text:
            raise SystemExit("Generated manifest is stale; regenerate it with the same arguments")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
    print(args.output)


if __name__ == "__main__":
    main()
