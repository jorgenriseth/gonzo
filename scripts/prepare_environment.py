"""Generate isolated release/development manifests without changing the default."""

import argparse
import copy
import json
import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load(path):
    with path.open("rb") as stream:
        return tomllib.load(stream)


def dump_tables(data, prefix=()):
    lines = []
    if prefix:
        lines.append("[" + ".".join(prefix) + "]")
    for key, value in data.items():
        if not re.fullmatch(r"[A-Za-z0-9_-]+", key):
            raise ValueError(f"Unsupported manifest key: {key}")
        if not isinstance(value, dict):
            lines.append(f"{key} = {json.dumps(value)}")
    lines.append("")
    for key, value in data.items():
        if isinstance(value, dict):
            lines.extend(dump_tables(value, (*prefix, key)))
    return lines


def manifest(library, development=False, channel=None):
    pixi = copy.deepcopy(load(ROOT / "pixi.toml"))
    policy = load(library / "conda-recipe/fsl.toml")
    name = policy["package"]["name"]
    dependencies = pixi["dependencies"]
    for package in policy["dependencies"]:
        dependencies.pop(package, None)
    dependencies["python"] = ">=3.11,<3.12"
    dependencies["simple-mri"] = ">=0.1.6,<0.2"
    pixi["pypi-dependencies"].pop("simple-mri", None)
    pixi["pypi-dependencies"].pop("gmri2fem", None)
    if development:
        dependencies.update(policy["dependencies"])
        pixi["pypi-dependencies"]["gmri2fem"] = {
            "path": str(library.resolve()), "editable": True,
        }
    else:
        dependencies[name] = f"=={policy['package']['version']}"
    pixi["workspace"]["name"] = "gonzo-development" if development else "gonzo-release"
    if channel:
        pixi["workspace"]["channels"].insert(0, Path(channel).resolve().as_uri())
    pixi["tasks"] = {}
    return pixi


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gmri2fem", type=Path, default=ROOT.parent / "gmri2fem")
    parser.add_argument("--development", action="store_true")
    parser.add_argument("--channel", type=Path, help="Local channel for pre-publication testing")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="Check an existing generated manifest")
    args = parser.parse_args()
    text = "# Generated by scripts/prepare_environment.py; do not edit.\n"
    text += "\n".join(dump_tables(manifest(args.gmri2fem, args.development, args.channel)))
    if args.check:
        if args.output.read_text() != text:
            raise SystemExit("Generated manifest is stale; regenerate it with the same arguments")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
    print(args.output)


if __name__ == "__main__":
    main()
